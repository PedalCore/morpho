  wire n3 = b[0];
  wire n4 = b[1];
  wire n5 = b[2];
  wire n6 = b[3];
  wire n7 = b[4];
  wire n8 = b[5];
  wire n9 = b[6];
  wire n10 = b[7];
  reg r11 = 1'b0;
  reg r12 = 1'b0;
  reg r13 = 1'b0;
  reg r14 = 1'b0;
  reg r15 = 1'b0;
  reg r16 = 1'b0;
  reg r17 = 1'b0;
  reg r18 = 1'b0;
  wire [1:0] l19 = 2'h1; wire w19 = l19[{n3}];
  wire [1:0] l20 = 2'h1; wire w20 = l20[{n4}];
  wire [1:0] l21 = 2'h1; wire w21 = l21[{n5}];
  wire [1:0] l22 = 2'h1; wire w22 = l22[{n6}];
  wire [1:0] l23 = 2'h1; wire w23 = l23[{n7}];
  wire [1:0] l24 = 2'h1; wire w24 = l24[{n8}];
  wire [1:0] l25 = 2'h1; wire w25 = l25[{n9}];
  wire [1:0] l26 = 2'h1; wire w26 = l26[{n10}];
  wire [3:0] l27 = 4'h9; wire w27 = l27[{w19, n2}];
  wire [3:0] l28 = 4'he; wire w28 = l28[{w19, n2}];
  wire [7:0] l29 = 8'h96; wire w29 = l29[{w28, w20, r11}];
  wire [7:0] l30 = 8'he8; wire w30 = l30[{w28, w20, r11}];
