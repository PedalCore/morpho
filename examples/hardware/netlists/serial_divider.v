  wire [7:0] l39 = 8'h96; wire w39 = l39[{w38, w25, r16}];
  wire [7:0] l40 = 8'he8; wire w40 = l40[{w38, w25, r16}];
  wire [7:0] l41 = 8'h96; wire w41 = l41[{w40, w26, r17}];
