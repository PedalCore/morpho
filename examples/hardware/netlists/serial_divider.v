  wire [7:0] l51 = 8'hca; wire w51 = l51[{w43, w41, r17}];
  always @(posedge clk) r11 <= w44;
  always @(posedge clk) r12 <= w45;
  always @(posedge clk) r13 <= w46;
  always @(posedge clk) r14 <= w47;
  always @(posedge clk) r15 <= w48;
  always @(posedge clk) r16 <= w49;
  always @(posedge clk) r17 <= w50;
  always @(posedge clk) r18 <= w51;
  assign q[0] = w43;
endmodule
